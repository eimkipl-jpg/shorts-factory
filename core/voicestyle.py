"""Голос автора для промтов: как сделать, чтобы текст озвучки звучал как живой человек, а не как нейросеть.

Три рычага: тон рассказчика (TONES), запрещённые штампы (BANNED) и правила разговорной речи (RULES).
Промт для нейросети собирается в core.scenario.make_prompt; «очеловечивающий» промт для готового черновика - polish_prompt.
"""

TONES = {
    "friend": ("Друг рассказывает",
               "Разговорно, как будто рассказываешь приятелю на кухне. Можно «слушай», «короче», «ну», «вот». "
               "Личная оценка («мне это до сих пор не нравится»), лёгкое удивление, без пафоса."),
    "dry": ("Сухая ирония",
            "Спокойно, почти без эмоций, факт и сухой комментарий поверх. Ни одного восклицательного знака. "
            "Шутка в недосказанности, а не в объяснении. Короткие фразы."),
    "meme": ("Мем-обзор",
             "Быстро, резко, с абсурдными сравнениями и интернет-культурой. Неожиданные повороты, "
             "обрывы на самом интересном. Не объясняй шутку, не оправдывайся."),
    "doc": ("Спокойная документалка",
            "Ровный темп, точные детали (даты, имена, цифры, места). Без крика и суперлативов. "
            "Интерес держится на фактах, а не на интонации."),
    "story": ("Мини-история",
              "Завязка, поворот, развязка, как маленький рассказ. Герой и конкретная ситуация вместо общих слов. "
              "Концовка без морали."),
}

DEFAULT_TONE = "friend"

BANNED = [
    "Знаете ли вы", "Ты знал, что", "А вы знали", "В этом видео", "Сегодня мы поговорим", "Давайте разберёмся",
    "Давай разберёмся", "Погрузимся", "Удивительный", "Невероятный", "Потрясающий", "Поистине", "Своего рода",
    "Не секрет, что", "Стоит отметить", "Важно понимать", "Важно помнить", "В современном мире", "В наше время",
    "Это не просто ... это", "А вот что интересно", "Вот почему это важно", "Подписывайся, чтобы не пропустить",
    "Ставь лайк", "Оказывается", "Является", "Таким образом", "Подводя итог",
]

RULES = """- Пиши НА СЛУХ: так, как человек говорит вслух, а не пишет статью. Короткие фразы вперемешку с длинными, длина сцен разная.
- Конкретика вместо общих слов: имя, число, предмет, место, деталь. Один точный факт лучше трёх общих утверждений.
- Хук: первая фраза - середина действия, парадокс или странная деталь. Не вопрос «знали ли вы?» и не анонс темы.
- Не объясняй шутку и не пересказывай сказанное. Не подводи мораль в конце. Лучше оборвать на неожиданной детали или вернуться к началу.
- Не начинай две соседние сцены одним и тем же словом. Не строй всё по одной схеме (вопрос - ответ - вывод).
- Без списков из трёх однородных слов, без пафосных тире, без риторических вопросов подряд, без канцелярита и слов вроде «является», «данный», «осуществлять».
- Допустима неидеальность живой речи: неполное предложение, «ну», «вот», «короче», но в меру, а не в каждой фразе.
- Призыв (cta) - короткий и в тоне ролика, не «Подписывайся и ставь лайк». Внутри text призывов нет.
- Для озвучки: без эмодзи и скобок, числа словами, без аббревиатур, которые не произносятся."""

BEFORE_AFTER = (
    "Плохо: «Удивительный факт: на Венере сутки длиннее, чем год! Давайте разберёмся, почему так происходит».\n"
    "Хорошо: «На Венере вы бы не дожили до первого рассвета. Год там кончается раньше, чем день».\n"
    "Плохо: «Этот кот является настоящей звездой интернета и покорил миллионы сердец».\n"
    "Хорошо: «Кота зовут Борис. Весит девять кило и пять лет подряд рушит один и тот же диван»."
)


def tone_block(tone: str | None) -> str:
    key = tone if tone in TONES else None
    if not key:
        return ""
    name, desc = TONES[key]
    return f"ТОН РАССКАЗЧИКА: {name}. {desc}\n"


def style_rules(tone: str | None = None) -> str:
    """Блок «как писать» для промта."""
    banned = "; ".join(f"«{b}»" for b in BANNED)
    return (
        f"{tone_block(tone)}\n"
        f"КАК ПИСАТЬ ТЕКСТ (чтобы не звучало как нейросеть)\n{RULES}\n"
        f"- СТОП-СЛОВА, не используй: {banned}.\n"
        f"- Калибровка тона на примерах:\n{BEFORE_AFTER}\n"
        "- Перед ответом перечитай каждую фразу вслух. Если звучит как статья, реклама или школьное сочинение - перепиши. "
        "Проверь: нет ли стоп-слов, нет ли двух соседних сцен с одинаковым началом, есть ли в каждой сцене конкретная деталь, "
        "и главное - читается ли весь текст подряд как один связный рассказ (каждая сцена продолжает предыдущую, есть связки «и», «но», «поэтому», «а»)."
    )


def polish_prompt(tone: str | None = None) -> str:
    """Второй проход: очеловечить готовый JSON, не трогая технические поля."""
    return f"""Ниже сценарий короткого вертикального видео в формате JSON. Перепиши в нём ТОЛЬКО тексты: scenes[].text, hook, cta, title, description,
чтобы они звучали как речь живого человека, а не как нейросеть, и склеивались в один связный рассказ: добавь связки между сценами, объедини
обрывочные факты, но смысл и порядок сцен сохрани. Все остальные поля и структуру JSON оставь без изменений
(theme, own, start, seconds, sfx, voice, music, style и т.д.), число сцен и их порядок не меняй. Верни ТОЛЬКО JSON, без пояснений и без ```.

{style_rules(tone)}

СЦЕНАРИЙ:
<вставьте сюда JSON>
"""
